#!/usr/bin/env bash
#
# run-gl-smoke.sh - Build and run the ATI Radeon host-GL smoke test against a
# prepared QEMU tree (default vendor/qemu after scripts/build-qemu.sh).
#
#   ati/tests/run-gl-smoke.sh [QEMU_SOURCE_DIR] [OUT_DIR]
#
# Uses the tree's own hw/display/ati_gl.c and ati_gl.h and the shader sources
# of its hw/display/ati_glr.c, so it checks exactly what qemu-system-ppc
# compiles. Needs a logged-in macOS session with a GPU (CGL context).

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
QEMU_SRC="${1:-$ROOT_DIR/vendor/qemu}"
OUT_DIR="${2:-$ROOT_DIR/output/ati-gl-smoke}"
DISPLAY_DIR="$QEMU_SRC/hw/display"

for f in ati_gl.c ati_gl.h ati_glr.c; do
  [ -f "$DISPLAY_DIR/$f" ] || { echo "missing $DISPLAY_DIR/$f (run scripts/build-qemu.sh)" >&2; exit 1; }
done
mkdir -p "$OUT_DIR"

# Copy the two shader string literals (vs_src, fs_src) out of ati_glr.c.
python3 -I - "$DISPLAY_DIR/ati_glr.c" "$OUT_DIR/ati_gl_smoke_shaders.h" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
out = ["/* generated by run-gl-smoke.sh from ati_glr.c */"]
for name in ("vs_src", "fs_src"):
    m = re.search(r"static const char \*" + name + r" =\n(.*?);\n", src, re.S)
    if not m:
        sys.exit(f"{name} not found in ati_glr.c")
    out.append(f"static const char *{name} =\n{m.group(1)};")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
PY

cc -std=gnu11 -O1 -Wall -Wextra -Wno-unused-parameter \
  -I"$DISPLAY_DIR" -I"$OUT_DIR" \
  -o "$OUT_DIR/ati_gl_smoke" \
  "$ROOT_DIR/ati/tests/ati_gl_smoke.c" "$DISPLAY_DIR/ati_gl.c" -lpthread
"$OUT_DIR/ati_gl_smoke"
